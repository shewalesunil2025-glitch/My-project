export const demoTagline = (lang: DemoLang) => words[lang].tagline;

const accounts = (svc: ServiceDef) => svc.connect.map((p) => providerInfo[p].name).join(" & ");

/**
 * The video's narration, one line per part of the video. The picture follows the same
 * parts in the same order (see components/demo/Film.tsx).
 */
export function demoScript(svc: ServiceDef, mode: DemoMode, lang: DemoLang): string[] {
  const w = words[lang];
  const trial = inTrial(svc.id);
  const parts =
    mode === "talk"
      ? [w.tagline, `${svc.name}: ${w.about[svc.id] ?? ""}`, w.ask(svc.name), trial ? w.trial : w.pay, w.details, svc.connect.length ? w.connect(accounts(svc)) : "", `${w.done(svc.name)} ${w.tagline}`]
      : [w.tagline, w.intro, w.open(svc.name), trial ? w.mtrial : w.mpay, w.fill, svc.connect.length ? w.mconnect(accounts(svc)) : "", w.activate];
  return parts;
}

/** The parts of a video (same for every language): which picture each part shows. */
export const demoParts = (mode: DemoMode) =>
  mode === "talk" ? (["intro", "about", "ask", "price", "details", "connect", "done"] as const) : (["intro", "manual", "services", "buy", "details", "connect", "activate"] as const);
